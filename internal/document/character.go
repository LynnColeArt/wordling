var vgaControl = []rune(vgaControlGlyphs)
var vgaHigh = []rune(vgaHighGlyphs)

func CharacterGlyph(set, number byte) string {
	if set == 0 && number >= 32 && number <= 126 {
		return string(rune(number))
	}
	if int(set) >= len(characterVGACells) || int(number) >= len(characterVGACells[set]) {
		return "■"
	}
	cell := characterVGACells[set][number]
	switch {
	case cell < 32:
		return string(vgaControl[cell])
	case cell == 127:
		return "⌂"
	case cell >= 128:
		return string(vgaHigh[cell-128])
	default:
		return string(rune(cell))
	}
}

// CharacterBytes returns one native printable character. Set zero is ASCII.
func CharacterBytes(set, number byte) []byte {
	if set == 0 && number >= 32 && number <= 126 {
		return []byte{number}
	}
	if !validExtendedCharacter(set, number) {
		return nil
	}
	return []byte{0xc0, number, set, 0xc0}
}

func validExtendedCharacter(set, number byte) bool {
	return set > 0 && int(set) < len(characterVGACells) && int(number) < len(characterVGACells[set])
}

// IsCharacter distinguishes printable owners from native formatting codes.
func (k Kind) IsCharacter() bool { return k == ASCII || k == ExtendedCharacter || k == HardSpace }

// CharacterText is the pinned DOS editing-screen glyph, independent of the stored identity.
func (t Token) CharacterText() string {
	if !t.Kind.IsCharacter() || identify(t.Raw) != t.Kind {
		return ""
	}
	return displayText(t.Kind, t.Raw, false)
}

// RevealCharacter expands the current extended owner in the lower DOS pane.
// Off-caret owners use their normal glyph instead.
func (t Token) RevealCharacter() string {
	if t.Kind != ExtendedCharacter || identify(t.Raw) != ExtendedCharacter {
		return t.CharacterText()
	}
	return fmt.Sprintf("[%s:%d,%d]", t.CharacterText(), t.Raw[2], t.Raw[1])
}

// IsExtendedCharacter checks a complete native printable owner.
func IsExtendedCharacter(raw []byte) bool { return identify(raw) == ExtendedCharacter }
