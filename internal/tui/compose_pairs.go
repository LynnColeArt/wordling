func lookupComposePair(pair string) (composeCharacter, bool) {
	if len(pair) != 2 {
		return composeCharacter{}, false
	}
	for _, spelling := range []string{pair, pair[1:] + pair[:1]} {
		for set, pairs := range composePairs {
			if number, ok := pairs[spelling]; ok {
				return composeCharacter{byte(set), number}, true
			}
		}
	}
	return composeCharacter{}, false
}
